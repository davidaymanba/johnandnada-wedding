// Builds the N & J monogram as real SVG outline paths (so DrawSVG can trace them).
// Run: npm run monogram  → writes content/monogram.ts (add --preview for an SVG proof)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import opentype from "opentype.js";

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fontPath = (pkg, file) => path.join(path.dirname(require.resolve(`${pkg}/package.json`)), "files", file);

const serif = opentype.parse(fs.readFileSync(fontPath("@fontsource/cormorant-garamond", "cormorant-garamond-latin-300-normal.woff")).buffer);
const script = opentype.parse(fs.readFileSync(fontPath("@fontsource/pinyon-script", "pinyon-script-latin-400-normal.woff")).buffer);

const W = 200;
const H = 260;

function glyph(font, ch, size, cx, baseline) {
  const g = font.charToGlyph(ch);
  const p = g.getPath(0, 0, size);
  const bb = p.getBoundingBox();
  const dx = cx - (bb.x1 + bb.x2) / 2;
  return font.getPath(ch, dx, baseline, size).toPathData(2);
}

const N = glyph(serif, "N", 100, 72, 152);
const J = glyph(serif, "J", 100, 130, 196);
const amp = glyph(script, "&", 60, 102, 182);

// Gothic arch frame, echoing the church doors guests knock on.
const arch = (inset) => {
  const l = 14 + inset, r = W - 14 - inset, top = 18 + inset * 1.25, spring = 112, base = 248 - inset * 0.4;
  const mid = W / 2;
  return `M${l} ${base}V${spring}C${l} ${spring - 52} ${mid - 46} ${top + 22} ${mid} ${top}C${mid + 46} ${top + 22} ${r} ${spring - 52} ${r} ${spring}V${base}`;
};
const outer = arch(0);
const inner = arch(7);
const base = `M6 ${248}H${W - 6}`;
const cross = `M100 2V20M93 8.5H107`;

// A standalone ampersand (for the names), cropped to its own box.
const ampGlyph = script.getPath("&", 0, 0, 100);
const ab = ampGlyph.getBoundingBox();
const pad = 4;
const ampSolo = {
  viewBox: `0 0 ${Math.ceil(ab.x2 - ab.x1 + pad * 2)} ${Math.ceil(ab.y2 - ab.y1 + pad * 2)}`,
  d: script.getPath("&", pad - ab.x1, pad - ab.y1, 100).toPathData(2),
};

const out = { viewBox: `0 0 ${W} ${H}`, N, J, amp, outer, inner, base, cross, ampSolo };
fs.writeFileSync(
  path.join(root, "content/monogram.ts"),
  `// Generated by scripts/build-monogram.mjs — do not edit by hand.\nexport const monogram = ${JSON.stringify(out, null, 2)} as const;\n`,
);

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${out.viewBox}" width="${W * 3}" height="${H * 3}">
<rect width="100%" height="100%" fill="#1C2230"/>
<g fill="none" stroke="#C8A96A" stroke-width="1"><path d="${outer}"/><path d="${inner}" stroke-width=".6"/><path d="${base}" stroke-width=".6"/><path d="${cross}"/></g>
<path d="${N}" fill="#F0EEE9"/><path d="${J}" fill="#F0EEE9"/><path d="${amp}" fill="#C8A96A"/>
</svg>`;
if (process.argv.includes("--preview")) fs.writeFileSync(path.join(root, "monogram-preview.svg"), svg);
console.log("monogram written");
